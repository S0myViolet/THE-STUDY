export function viewBox(v: MapView): string {
  const a = project(v.lon[0], v.lat[1]);
  const b = project(v.lon[1], v.lat[0]);
  return `${a.x} ${a.y} ${b.x - a.x} ${b.y - a.y}`;
}

/** Scale factor relative to the world view, used to keep dots and labels legible when zoomed. */
export function viewScale(v: MapView): number {
  return (v.lon[1] - v.lon[0]) / 360;
}

export function pathFor(points: LonLat[]): string {
  return points.map(([lon, lat], i) => {
    const p = project(lon, lat);
    return `${i ? "L" : "M"}${p.x.toFixed(1)} ${p.y.toFixed(1)}`;
  }).join(" ") + " Z";
}
