/**
 * Coarse, hand-authored continent outlines for the Archive world map.
 * Equirectangular projection. Points are [lon, lat]. The outlines are
 * deliberately simple: recognisable, not cartographic.
 */

export type LonLat = [number, number];

export const MAP_W = 1000;
export const MAP_H = 500;

export function project(lon: number, lat: number, w = MAP_W, h = MAP_H): { x: number; y: number } {
  return { x: ((lon + 180) / 360) * w, y: ((90 - lat) / 180) * h };
}

